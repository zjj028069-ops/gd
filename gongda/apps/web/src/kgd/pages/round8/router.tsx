import { DefectList, DefectTrendPage, FullInspection, PurchaseLineList, PurchaseTestList, QualityReport, SpecList, SpotCheckList, SpotLineList } from '../quality/pages';
import { OutContentList, OutOrderDetail, OutOrderForm, OutOrderList, OutReceiptList, OutSettlementList } from '../outsource/pages';
import { MachineList, ProduceDictionary, StationSetting } from '../machine/pages';
import { ContractReport, CostReport, InventorySummary, MachineReport, SalesStatement } from '../reports-biz/pages';
import { LeanSetting, LeanWorkstation, MeetingDetail, MeetingList, MeetingTodo, PatrolList, RectifyCenter } from '../lean/pages';
import { AlarmList, IotScenes, IotSetting, SensorList } from '../iot/pages';
import { BreakdownList, DeviceList, EquipList, EquipSetting, MaintReport, QrList, RepairList } from '../equip/pages';

export function resolveRound8Page(pathname: string) {
  if (pathname === '/waste_item/list') return <DefectList />;
  if (pathname === '/work_quality_testing/list') return <FullInspection />;
  if (pathname === '/spot_check/list') return <SpotCheckList />;
  if (pathname === '/spot_check_item/list') return <SpotLineList />;
  if (pathname === '/material_test/list') return <PurchaseTestList />;
  if (pathname === '/material_test_item_list/list') return <PurchaseLineList />;
  if (pathname === '/material_test_content/list') return <SpecList />;
  if (pathname === '/waste_analysis') return <DefectTrendPage />;
  if (pathname === '/waste_key_analysis') return <QualityReport kind="pareto" />;
  if (pathname === '/waste_detail') return <QualityReport kind="detail" />;
  if (pathname === '/material_test_report') return <QualityReport kind="purchase" />;
  if (pathname === '/spot_check_report') return <QualityReport kind="spot" />;
  if (pathname === '/scrap_rework_statistics_report') return <QualityReport kind="scrap" />;
  if (pathname === '/OutWorkOrder/list') return <OutOrderList />;
  if (pathname === '/OutWorkOrder/add') return <OutOrderForm />;
  if (pathname.startsWith('/OutWorkOrder/edit/')) return <OutOrderForm id={pathname.split('/').pop()} />;
  if (pathname.startsWith('/OutWorkOrder/detail/')) return <OutOrderDetail id={pathname.split('/').pop() ?? ''} />;
  if (pathname === '/outsourcing_receipt/list') return <OutReceiptList />;
  if (pathname === '/Outsourcing_settlement/list') return <OutSettlementList />;
  if (pathname === '/outsourcing_content/list') return <OutContentList />;
  if (pathname === '/machine_platform/list') return <MachineList />;
  if (pathname === '/setting/produce/dictionary') return <ProduceDictionary />;
  if (pathname === '/setting/produce/station') return <StationSetting />;
  if (pathname === '/sales_statement') return <SalesStatement />;
  if (pathname === '/contract_report') return <ContractReport />;
  if (pathname === '/produce_bill_cost') return <CostReport />;
  if (pathname === '/inventory_summary') return <InventorySummary />;
  if (pathname === '/drilling_crew_statement/list' || pathname === '/drilling_crew_statement') return <MachineReport />;
  if (pathname === '/LeanProductionReportChart/ReportChart') return <LeanWorkstation />;
  if (pathname === '/lean_production_todo/list') return <RectifyCenter />;
  if (pathname === '/meeting/list') return <MeetingList />;
  if (pathname.startsWith('/meeting/detail/')) return <MeetingDetail />;
  if (pathname === '/meetingTodo/list') return <MeetingTodo />;
  if (pathname === '/onsite_inspection/list') return <PatrolList />;
  if (pathname === '/setting/lean_production') return <LeanSetting />;
  if (pathname === '/device_iot/list') return <IotScenes />;
  if (pathname === '/device_sensor/list') return <SensorList />;
  if (pathname === '/alarm_record/list') return <AlarmList />;
  if (pathname === '/setting/smart_device/setting') return <IotSetting />;
  if (pathname === '/inspection_plan/list') return <EquipList path="/api/equip/plans" title="维保计划" columns={[['title', '计划名称'], ['category', '类别'], ['cycle_text', '周期'], ['executor_name', '执行人'], ['status', '状态']]} />;
  if (pathname === '/inspection_task/list') return <EquipList path="/api/equip/tasks" title="维保任务" columns={[['plan_title', '计划'], ['task_date', '任务日期'], ['executor_name', '执行人'], ['status', '状态'], ['device_count', '设备数']]} />;
  if (pathname === '/inspection_record/list') return <EquipList path="/api/equip/records" title="维保记录" columns={[['plan_title', '计划'], ['device_name', '设备'], ['result', '结果'], ['executor_name', '执行人'], ['executed_at', '执行时间']]} />;
  if (pathname === '/inspection_breakdown/list') return <BreakdownList />;
  if (pathname === '/inspection_content/list') return <EquipList path="/api/equip/contents" title="维保内容" columns={[['title', '标题'], ['item_count', '检查项'], ['note', '备注'], ['creator_name', '创建人']]} />;
  if (pathname === '/point_inspection_plan/list') return <EquipList path="/api/equip/pi-plans" title="点检计划" columns={[['device_name', '设备'], ['device_code', '设备编号'], ['executor_name', '执行人'], ['content_title', '内容'], ['status', '状态']]} />;
  if (pathname === '/point_inspection_record/list') return <EquipList path="/api/equip/pi-records" title="点检记录" columns={[['device_name', '设备'], ['inspector_name', '点检人'], ['content_name', '内容'], ['normal_count', '正常'], ['abnormal_count', '异常'], ['checked_at', '点检时间']]} />;
  if (pathname === '/device_order/list') return <RepairList />;
  if (pathname === '/device/list') return <DeviceList />;
  if (pathname === '/device_qr_code/list') return <QrList />;
  if (pathname === '/setting/inspection/setting') return <EquipSetting />;
  if (pathname === '/device_maintenance_analysis') return <MaintReport kind="repair" />;
  if (pathname === '/maintenance_workload_statistics') return <MaintReport kind="workload" />;
  if (pathname === '/maintenance_plan_statistics') return <MaintReport kind="plans" />;
  return null;
}
