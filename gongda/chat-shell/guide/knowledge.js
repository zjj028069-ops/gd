  function normalize(s) {
    return String(s || "")
      .toLowerCase()
      .replace(/\s+/g, "")
      .replace(/[？?！!。，,、]/g, "");
  }

  /**
   * 关键词打分匹配；返回最佳专题或 null
   */
  function matchGuide(text) {
    const q = normalize(text);
    if (!q) return null;
    let best = null;
    let bestScore = 0;
    GUIDE_TOPICS.forEach((t) => {
      let score = 0;
      (t.keywords || []).forEach((kw) => {
        const k = normalize(kw);
        if (!k) return;
        if (q === k) score += 12;
        else if (q.indexOf(k) !== -1) score += 8;
        else if (k.length >= 2 && q.indexOf(k.slice(0, Math.min(4, k.length))) !== -1) score += 2;
      });
      // 标题轻量加分
      const tn = normalize(t.title);
      if (tn && q.indexOf(tn) !== -1) score += 6;
      if (score > bestScore) {
        bestScore = score;
        best = t;
      }
    });
    if (bestScore < 4) return null;
    return best;
  }

  function getTopicById(id) {
    return GUIDE_TOPICS.find((t) => t.id === id) || null;
  }

  function catalogTopics() {
    return GUIDE_CATALOG.map(getTopicById).filter(Boolean);
  }

